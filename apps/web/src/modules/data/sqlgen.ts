/** Visual schema model → SQL DDL (PostgreSQL / MySQL) and migration diffs. Pure and unit-tested. */

export type Dialect = "postgres" | "mysql";
export const COLUMN_TYPES = ["uuid", "serial", "integer", "bigint", "numeric", "boolean", "text", "varchar", "date", "timestamptz", "jsonb"] as const;
export type ColumnType = (typeof COLUMN_TYPES)[number];
export type OnDelete = "cascade" | "restrict" | "set null";

export interface Column {
  id: string;
  name: string;
  type: ColumnType;
  length?: number;
  nullable: boolean;
  unique: boolean;
  pk: boolean;
  default?: string;
  references?: { table: string; column: string; onDelete: OnDelete } | null;
}
export interface Table {
  id: string;
  name: string;
  columns: Column[];
  x: number;
  y: number;
}
export interface DbSchema {
  version: 1;
  dialect: Dialect;
  tables: Table[];
  /** Snapshot of the schema as it was last applied to a real database (for migrations). */
  applied?: { tables: Table[]; at: string } | null;
}

const IDENT = /^[A-Za-z_][A-Za-z0-9_]{0,62}$/;
export const q = (d: Dialect, name: string) => (d === "postgres" ? `"${name.replace(/"/g, '""')}"` : `\`${name.replace(/`/g, "``")}\``);

export function sqlType(d: Dialect, c: Column): string {
  switch (c.type) {
    case "uuid": return d === "postgres" ? "uuid" : "char(36)";
    case "serial": return d === "postgres" ? "integer GENERATED BY DEFAULT AS IDENTITY" : "int AUTO_INCREMENT";
    case "integer": return d === "postgres" ? "integer" : "int";
    case "bigint": return "bigint";
    case "numeric": return "numeric(12,2)";
    case "boolean": return d === "postgres" ? "boolean" : "tinyint(1)";
    case "text": return "text";
    case "varchar": return `varchar(${c.length && c.length > 0 ? Math.min(c.length, 10485760) : 255})`;
    case "date": return "date";
    case "timestamptz": return d === "postgres" ? "timestamptz" : "datetime(3)";
    case "jsonb": return d === "postgres" ? "jsonb" : "json";
  }
}

function defaultSql(d: Dialect, c: Column): string {
  const v = c.default?.trim();
  if (!v) return "";
  if (/^now\(\)$/i.test(v)) return ` DEFAULT ${d === "postgres" ? "now()" : "CURRENT_TIMESTAMP(3)"}`;
  if (/^gen_random_uuid\(\)$/i.test(v)) return d === "postgres" ? " DEFAULT gen_random_uuid()" : " DEFAULT (uuid())";
  if (/^(true|false|null|-?\d+(\.\d+)?)$/i.test(v)) return ` DEFAULT ${d === "mysql" && /^(true|false)$/i.test(v) ? (v.toLowerCase() === "true" ? "1" : "0") : v}`;
  return ` DEFAULT '${v.replace(/'/g, "''")}'`;
}

export function columnSql(d: Dialect, c: Column): string {
  return `${q(d, c.name)} ${sqlType(d, c)}${c.nullable || c.pk ? "" : " NOT NULL"}${defaultSql(d, c)}${c.unique && !c.pk ? " UNIQUE" : ""}`;
}

const fkName = (t: string, c: string) => `fk_${t}_${c}`.slice(0, 63);
function fkSql(d: Dialect, t: Table, c: Column): string {
  const r = c.references!;
  return `CONSTRAINT ${q(d, fkName(t.name, c.name))} FOREIGN KEY (${q(d, c.name)}) REFERENCES ${q(d, r.table)} (${q(d, r.column)}) ON DELETE ${r.onDelete.toUpperCase()}`;
}

/** Problems that would make the generated SQL invalid. */
export function validateSchema(s: DbSchema): string[] {
  const out: string[] = [];
  const names = new Set<string>();
  for (const t of s.tables) {
    if (!IDENT.test(t.name)) out.push(`Table name "${t.name}" must start with a letter or _ and use only letters, digits and _`);
    if (names.has(t.name)) out.push(`Duplicate table "${t.name}"`);
    names.add(t.name);
    if (!t.columns.length) out.push(`Table "${t.name}" has no columns`);
    if (!t.columns.some((c) => c.pk)) out.push(`Table "${t.name}" has no primary key`);
    const cols = new Set<string>();
    for (const c of t.columns) {
      if (!IDENT.test(c.name)) out.push(`${t.name}.${c.name}: invalid column name`);
      if (cols.has(c.name)) out.push(`${t.name}: duplicate column "${c.name}"`);
      cols.add(c.name);
      if (c.references) {
        const target = s.tables.find((x) => x.name === c.references!.table);
        const tc = target?.columns.find((x) => x.name === c.references!.column);
        if (!target || !tc) out.push(`${t.name}.${c.name} references a missing column ${c.references.table}.${c.references.column}`);
        else if (!tc.pk && !tc.unique) out.push(`${t.name}.${c.name} must reference a primary-key or unique column`);
        if (c.references.onDelete === "set null" && !c.nullable) out.push(`${t.name}.${c.name}: ON DELETE SET NULL needs a nullable column`);
      }
    }
  }
  return out;
}

/** Order tables so referenced tables come first; foreign keys in cycles are added afterwards. */
function ordered(tables: Table[]): { order: Table[]; deferred: Array<[Table, Column]> } {
  const byName = new Map(tables.map((t) => [t.name, t]));
  const done = new Set<string>();
  const visiting = new Set<string>();
  const order: Table[] = [];
  const deferred: Array<[Table, Column]> = [];
  const visit = (t: Table) => {
    if (done.has(t.name)) return;
    visiting.add(t.name);
    for (const c of t.columns) {
      const ref = c.references?.table;
      if (!ref || ref === t.name || !byName.has(ref)) continue;
      if (visiting.has(ref)) deferred.push([t, c]);
      else visit(byName.get(ref)!);
    }
    visiting.delete(t.name);
    done.add(t.name);
    order.push(t);
  };
  tables.forEach(visit);
  return { order, deferred };
}

export function createTableSql(d: Dialect, t: Table, skipFk: (c: Column) => boolean = () => false): string {
  const lines = t.columns.map((c) => `  ${columnSql(d, c)}`);
  const pks = t.columns.filter((c) => c.pk);
  if (pks.length) lines.push(`  PRIMARY KEY (${pks.map((c) => q(d, c.name)).join(", ")})`);
  for (const c of t.columns) if (c.references && !skipFk(c)) lines.push(`  ${fkSql(d, t, c)}`);
  return `CREATE TABLE ${q(d, t.name)} (\n${lines.join(",\n")}\n)${d === "mysql" ? " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4" : ""};`;
}

export function createSchemaSql(s: DbSchema): string {
  const d = s.dialect;
  const { order, deferred } = ordered(s.tables);
  const isDeferred = (t: Table, c: Column) => deferred.some(([dt, dc]) => dt.id === t.id && dc.id === c.id);
  const parts = [`-- Generated by Multi-functional Creator (${d})`, ...(d === "postgres" && s.tables.some((t) => t.columns.some((c) => /gen_random_uuid/i.test(c.default ?? ""))) ? ["CREATE EXTENSION IF NOT EXISTS pgcrypto;"] : [])];
  for (const t of order) parts.push(createTableSql(d, t, (c) => isDeferred(t, c)));
  for (const [t, c] of deferred) parts.push(`ALTER TABLE ${q(d, t.name)} ADD ${fkSql(d, t, c)};`);
  for (const t of order) for (const c of t.columns) if (c.references) parts.push(`CREATE INDEX ${q(d, `idx_${t.name}_${c.name}`.slice(0, 63))} ON ${q(d, t.name)} (${q(d, c.name)});`);
  return parts.join("\n\n") + "\n";
}

/** Migration from the applied snapshot to the current design. Renames are detected by stable ids. */
export function diffSql(from: Table[], to: Table[], d: Dialect): string[] {
  const out: string[] = [];
  const fromById = new Map(from.map((t) => [t.id, t]));
  const toIds = new Set(to.map((t) => t.id));
  for (const old of from) if (!toIds.has(old.id)) out.push(`DROP TABLE ${q(d, old.name)};`);
  for (const t of to) {
    const old = fromById.get(t.id);
    if (!old) {
      out.push(createTableSql(d, t));
      continue;
    }
    if (old.name !== t.name) out.push(`ALTER TABLE ${q(d, old.name)} RENAME TO ${q(d, t.name)};`);
    const tn = q(d, t.name);
    const oldCols = new Map(old.columns.map((c) => [c.id, c]));
    const newIds = new Set(t.columns.map((c) => c.id));
    for (const oc of old.columns) {
      if (newIds.has(oc.id)) continue;
      if (oc.references) out.push(d === "postgres" ? `ALTER TABLE ${tn} DROP CONSTRAINT IF EXISTS ${q(d, fkName(old.name, oc.name))};` : `ALTER TABLE ${tn} DROP FOREIGN KEY ${q(d, fkName(old.name, oc.name))};`);
      out.push(`ALTER TABLE ${tn} DROP COLUMN ${q(d, oc.name)};`);
    }
    for (const c of t.columns) {
      const oc = oldCols.get(c.id);
      if (!oc) {
        out.push(`ALTER TABLE ${tn} ADD COLUMN ${columnSql(d, c)};`);
        if (c.references) out.push(`ALTER TABLE ${tn} ADD ${fkSql(d, t, c)};`);
        continue;
      }
      if (oc.name !== c.name) out.push(d === "postgres" ? `ALTER TABLE ${tn} RENAME COLUMN ${q(d, oc.name)} TO ${q(d, c.name)};` : `ALTER TABLE ${tn} RENAME COLUMN ${q(d, oc.name)} TO ${q(d, c.name)};`);
      const col = q(d, c.name);
      const typeChanged = sqlType(d, oc) !== sqlType(d, c);
      if (d === "mysql") {
        if (typeChanged || oc.nullable !== c.nullable || (oc.default ?? "") !== (c.default ?? "")) out.push(`ALTER TABLE ${tn} MODIFY COLUMN ${columnSql(d, { ...c, unique: false })};`);
      } else {
        if (typeChanged) out.push(`ALTER TABLE ${tn} ALTER COLUMN ${col} TYPE ${sqlType(d, c).replace(/ GENERATED.*$/, "")} USING ${col}::${sqlType(d, c).split(" ")[0]};`);
        if (oc.nullable !== c.nullable && !c.pk) out.push(`ALTER TABLE ${tn} ALTER COLUMN ${col} ${c.nullable ? "DROP NOT NULL" : "SET NOT NULL"};`);
        if ((oc.default ?? "") !== (c.default ?? "")) out.push(c.default ? `ALTER TABLE ${tn} ALTER COLUMN ${col}${defaultSql(d, c).replace(" DEFAULT", " SET DEFAULT")};` : `ALTER TABLE ${tn} ALTER COLUMN ${col} DROP DEFAULT;`);
      }
      const uq = `uq_${t.name}_${c.name}`.slice(0, 63);
      if (oc.unique !== c.unique && !c.pk) out.push(c.unique ? `ALTER TABLE ${tn} ADD CONSTRAINT ${q(d, uq)} UNIQUE (${col});` : d === "postgres" ? `ALTER TABLE ${tn} DROP CONSTRAINT IF EXISTS ${q(d, uq)};` : `ALTER TABLE ${tn} DROP INDEX ${q(d, uq)};`);
      const refKey = (x: Column) => (x.references ? `${x.references.table}.${x.references.column}.${x.references.onDelete}` : "");
      if (refKey(oc) !== refKey(c)) {
        if (oc.references) out.push(d === "postgres" ? `ALTER TABLE ${tn} DROP CONSTRAINT IF EXISTS ${q(d, fkName(old.name, oc.name))};` : `ALTER TABLE ${tn} DROP FOREIGN KEY ${q(d, fkName(old.name, oc.name))};`);
        if (c.references) out.push(`ALTER TABLE ${tn} ADD ${fkSql(d, t, c)};`);
      }
    }
  }
  return out;
}

let seq = 0;
export const sid = (p = "c") => `${p}_${Date.now().toString(36)}${(seq++).toString(36)}${Math.random().toString(36).slice(2, 6)}`;

export function newColumn(o: Partial<Column> = {}): Column {
  return { id: sid("c"), name: "column", type: "text", nullable: true, unique: false, pk: false, ...o };
}

export function newTable(name: string, x = 40, y = 40): Table {
  return {
    id: sid("t"),
    name,
    x,
    y,
    columns: [newColumn({ name: "id", type: "uuid", pk: true, nullable: false, default: "gen_random_uuid()" }), newColumn({ name: "created_at", type: "timestamptz", nullable: false, default: "now()" })],
  };
}

export function starterSchema(): DbSchema {
  const users = newTable("users", 40, 40);
  users.columns.splice(1, 0, newColumn({ name: "email", type: "varchar", length: 254, nullable: false, unique: true }), newColumn({ name: "name", type: "text" }));
  const orders = newTable("orders", 380, 60);
  orders.columns.splice(1, 0, newColumn({ name: "user_id", type: "uuid", nullable: false, references: { table: "users", column: "id", onDelete: "cascade" } }), newColumn({ name: "total", type: "numeric", nullable: false, default: "0" }), newColumn({ name: "status", type: "varchar", length: 20, nullable: false, default: "pending" }));
  return { version: 1, dialect: "postgres", tables: [users, orders], applied: null };
}

export function isDbSchema(d: unknown): d is DbSchema {
  const s = d as DbSchema;
  return !!s && Array.isArray(s.tables) && (s.dialect === "postgres" || s.dialect === "mysql");
}

/** Map a database's reported column type to the designer's portable types. */
export function mapColumnType(raw: string): { type: ColumnType; length?: number } {
  const t = raw.toLowerCase();
  const len = /\((\d+)\)/.exec(t)?.[1];
  if (t.includes("uuid") || t === "char(36)") return { type: "uuid" };
  if (t.startsWith("bigint")) return { type: "bigint" };
  if (/^(int|integer|smallint|mediumint|tinyint\((?!1\))|serial)/.test(t)) return { type: "integer" };
  if (/^(tinyint\(1\)|bool)/.test(t)) return { type: "boolean" };
  if (/^(numeric|decimal|real|double|float|money)/.test(t)) return { type: "numeric" };
  if (/^(character varying|varchar)/.test(t)) return { type: "varchar", length: len ? Number(len) : 255 };
  if (/^timestamp|^datetime/.test(t)) return { type: "timestamptz" };
  if (t === "date") return { type: "date" };
  if (/json/.test(t)) return { type: "jsonb" };
  return { type: "text" };
}

/** Reverse-engineer a live database (as read by the data browser) into a designer schema. */
export function importSchema(tables: Array<{ name: string; columns: Array<{ name: string; type: string; nullable: boolean; pk?: boolean; default?: string | null; references?: { table: string; column: string } | null }> }>, dialect: Dialect): DbSchema {
  const short = (n: string) => n.replace(/^public\./, "");
  const out: DbSchema = {
    version: 1,
    dialect,
    applied: null,
    tables: tables.map((tb) => ({
      id: sid("t"),
      name: short(tb.name),
      x: 0,
      y: 0,
      columns: tb.columns.map((c) => {
        const m = mapColumnType(c.type);
        const serial = /nextval\(/.test(c.default ?? "") || /auto_increment/i.test(c.default ?? "");
        return newColumn({
          name: c.name,
          type: serial ? "serial" : m.type,
          length: m.length,
          nullable: c.pk ? false : c.nullable,
          pk: !!c.pk,
          default: serial || !c.default ? undefined : c.default.replace(/::[a-z ]+$/i, ""),
          references: c.references ? { table: short(c.references.table), column: c.references.column, onDelete: "cascade" } : null,
        });
      }),
    })),
  };
  // Every snapshot imported from a live database is, by definition, already applied.
  out.applied = { tables: structuredClone(autoArrange(out).tables), at: new Date().toISOString() };
  return autoArrange(out);
}

/** Lay tables out left-to-right by foreign-key depth (referenced tables first), stacked in columns. */
export function autoArrange(s: DbSchema): DbSchema {
  const byName = new Map(s.tables.map((t) => [t.name, t]));
  const depth = new Map<string, number>();
  const visit = (t: Table, seen: Set<string>): number => {
    if (depth.has(t.name)) return depth.get(t.name)!;
    if (seen.has(t.name)) return 0;
    seen.add(t.name);
    const refs = t.columns.map((c) => c.references && byName.get(c.references.table)).filter((x): x is Table => !!x && x !== t);
    const d = refs.length ? Math.max(...refs.map((r) => visit(r, seen) + 1)) : 0;
    depth.set(t.name, d);
    return d;
  };
  s.tables.forEach((t) => visit(t, new Set()));
  const colY = new Map<number, number>();
  return {
    ...s,
    tables: s.tables.map((t) => {
      const d = depth.get(t.name) ?? 0;
      const y = colY.get(d) ?? 40;
      colY.set(d, y + 34 + t.columns.length * 24 + 50);
      return { ...t, x: 40 + d * 300, y };
    }),
  };
}

/** Copy of a table with fresh ids and a unique name. */
export function duplicateTable(s: DbSchema, id: string): Table | null {
  const src = s.tables.find((t) => t.id === id);
  if (!src) return null;
  let name = `${src.name}_copy`;
  for (let i = 2; s.tables.some((t) => t.name === name); i++) name = `${src.name}_copy${i}`;
  return { ...structuredClone(src), id: sid("t"), name, x: src.x + 40, y: src.y + 40, columns: src.columns.map((c) => ({ ...structuredClone(c), id: sid("c") })) };
}
